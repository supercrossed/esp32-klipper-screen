"""
Pre-render the UI font (Inter, OFL-1.1) into LVGL bitmap fonts.

    python tools/gen_fonts.py

Needs Pillow (with FreeType). Reads main/ui/fonts/inter_regular.ttf and
inter_bold.ttf and writes main/ui/fonts/inter_<weight>_<px>.c plus
inter_fonts.h, in LVGL's "fmt_txt" format (4 bits per pixel, no kerning).

Bitmap fonts draw several times faster than rendering the TTF at run time with
Tiny TTF, which matters for long scrolling lists. To add a size, put it in
SIZES and re-run; ui_font_bold(px) picks the nearest generated bold size.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "main", "ui", "fonts")

SIZES = {
    "regular": [16, 20, 24, 32, 48],
    "bold": [16, 18, 20, 22, 24, 26, 28, 30, 32, 40, 44],
}
# ASCII, Latin-1 (accented names), L/l with stroke (zł), en/em dash, quotes, bullet, ellipsis,
# currency signs (Spoolman prices: € ₩ ₹ ₽), trade mark (filament names)
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x141, 0x142), (0x2013, 0x2014), (0x2018, 0x201D), (0x2022, 0x2022), (0x2026, 0x2026),
          (0x20A9, 0x20A9), (0x20AC, 0x20AC), (0x20B9, 0x20B9), (0x20BD, 0x20BD), (0x2122, 0x2122)]


def render(font, ch):
    """-> (box_w, box_h, ofs_x, ofs_y, adv16, 4-bit pixel rows)"""
    adv16 = round(font.getlength(ch) * 16)
    l, t, r, b = font.getbbox(ch, anchor="ls")   # relative to the baseline origin, y down
    w, h = r - l, b - t
    if w <= 0 or h <= 0 or ch == " ":
        return 0, 0, 0, 0, adv16, []
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
    px = img.load()
    rows = [[min(15, (px[x, y] + 8) >> 4) for x in range(w)] for y in range(h)]
    # trim fully empty rows/columns so the box is tight
    while rows and not any(rows[0]): rows.pop(0); t += 1
    while rows and not any(rows[-1]): rows.pop(); b -= 1
    if not rows:
        return 0, 0, 0, 0, adv16, []
    while not any(r_[0] for r_ in rows): rows = [r_[1:] for r_ in rows]; l += 1
    while not any(r_[-1] for r_ in rows): rows = [r_[:-1] for r_ in rows]
    box_w, box_h = len(rows[0]), len(rows)
    return box_w, box_h, l, -b, adv16, rows


def pack(rows):
    """4 bpp, rows packed back to back (no per-row padding), high nibble first."""
    nib = [v for r in rows for v in r]
    if len(nib) % 2:
        nib.append(0)
    return bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))


def gen(weight, size):
    name = f"inter_{weight}_{size}"
    font = ImageFont.truetype(os.path.join(FONTS, f"inter_{weight}.ttf"), size)
    ascent, descent = font.getmetrics()
    bitmap = bytearray()
    dsc = ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 reserved */"]
    cmaps = []
    gid = 1
    for lo, hi in RANGES:
        cmaps.append(f"    {{.range_start = {lo}, .range_length = {hi - lo + 1}, .glyph_id_start = {gid}, "
                     f".unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
                     f".type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}}")
        for cp in range(lo, hi + 1):
            bw, bh, ox, oy, adv, rows = render(font, chr(cp))
            dsc.append(f"    {{.bitmap_index = {len(bitmap)}, .adv_w = {adv}, .box_w = {bw}, .box_h = {bh}, "
                       f".ofs_x = {ox}, .ofs_y = {oy}}} /* U+{cp:04X} */")
            bitmap += pack(rows)
            gid += 1
    hexrows = ",\n".join("    " + ", ".join(f"0x{v:02x}" for v in bitmap[i:i + 16]) for i in range(0, len(bitmap), 16))
    src = f"""/* Generated by tools/gen_fonts.py from Inter (OFL-1.1, see OFL.txt). Do not edit. */
#include "lvgl.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{hexrows}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{",\n".join(dsc)}
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
{",\n".join(cmaps)}
}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = {len(cmaps)},
    .bpp = 4,
    .kern_classes = 0,
    .bitmap_format = 0,
}};

const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
    .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = {-max(1, size // 12)},
    .underline_thickness = {max(1, size // 16)},
    .dsc = &font_dsc,
}};
"""
    with open(os.path.join(FONTS, name + ".c"), "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    return name, len(bitmap)


def main():
    names = []
    total = 0
    for weight, sizes in SIZES.items():
        for px in sizes:
            name, n = gen(weight, px)
            names.append((weight, px, name))
            total += n
            print(f"{name}: {n // 1024} KB bitmap")
    with open(os.path.join(FONTS, "inter_fonts.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Generated by tools/gen_fonts.py. Do not edit. */\n#pragma once\n#include \"lvgl.h\"\n\n")
        for _, _, name in names:
            f.write(f"extern const lv_font_t {name};\n")
        for weight in SIZES:
            f.write(f"\n#define INTER_{weight.upper()}_TABLE {{ \\\n")
            for w, px, name in names:
                if w == weight:
                    f.write(f"    {{ {px}, &{name} }}, \\\n")
            f.write("}\n")
    print(f"total {total // 1024} KB")


if __name__ == "__main__":
    main()
