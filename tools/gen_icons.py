ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "tools", ".cache")


def fetch(sub, name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path):
        url = f"{BASE}/{sub}/{name}"
        print("downloading", url)
        urllib.request.urlretrieve(url, path)
    return path


def main():
    ttf = fetch("fonts", "materialdesignicons-webfont.ttf")
    css = open(fetch("css", "materialdesignicons.css"), encoding="utf-8").read()
    with open(ttf, "rb") as f:
        if f.read(4) != b"\x00\x01\x00\x00":
            sys.exit("downloaded file is not a TrueType font")
    cps = dict(re.findall(r'\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"', css))
    missing = [n for n in ICONS.values() if n not in cps]
    if missing:
        sys.exit("unknown MDI icon names: " + ", ".join(missing))

    out_dir = os.path.join(ROOT, "main", "ui", "icons")
    os.makedirs(out_dir, exist_ok=True)
    shutil.copyfile(ttf, os.path.join(out_dir, "mdi.ttf"))

    with open(os.path.join(ROOT, "main", "ui", "icons.h"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/gen_icons.py from Material Design Icons %s (Apache-2.0). Do not edit. */\n" % MDI_VER)
        f.write("#pragma once\n\n")
        for macro, name in ICONS.items():
            esc = "".join(f"\\x{b:02X}" for b in chr(int(cps[name], 16)).encode("utf-8"))
            f.write(f'#define ICON_{macro:<12} "{esc}"   /* mdi-{name} */\n')
    print(f"ok: {len(ICONS)} icons, font {os.path.getsize(ttf)//1024} KB")


if __name__ == "__main__":
    main()
